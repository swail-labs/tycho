def _commands_dir(repo: Path, scope: str = REPO) -> Path:
    # Repo scope keeps `<repo>/.claude/commands` (not `state.root_for`); changing it would
    # move every already-installed command file.
    return (claude_dir(repo, GLOBAL) if scope == GLOBAL else repo / ".claude") / "commands"


def _q(s: str) -> str:
    """Quote a YAML frontmatter value. A bare colon-space in a description reads as a
    nested mapping and breaks Claude Code's parse, so always quote."""
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _slash_body(description: str, cli_args: str, argument_hint: str = "") -> str:
    """A prompt-style command file backed by the real CLI: relies only on the stable
    `.claude/commands/*.md` convention and `$ARGUMENTS`, not on `!`-exec / `allowed-tools`
    glob matching against a quoted interpreter path."""
    # The YAML frontmatter MUST start at line 1 or Claude Code won't parse it, so the
    # marker goes in the body, not above it.
    hint = f"argument-hint: {_q(argument_hint)}\n" if argument_hint else ""
    return (
        "---\n"
        f"description: {_q(description)}\n{hint}"
        "---\n\n"
        f"{_SLASH_MARKER}\n\n"
        "Run this exact command with the Bash tool and show its output verbatim - "
        "nothing else, no commentary:\n\n"
        f"`{_command_for(cli_args)}`\n\n"
        "This is Tycho's own CLI (it also runs standalone in your terminal); it never edits code.\n"
    )


# The scope commands: (description, cli action, argument-hint). set/add/remove take path
# globs, which MUST be single-quoted so the shell doesn't expand them before Tycho stores
# them — the body says so explicitly.
_SCOPE_SLASH = {
    "scope-list": ("List the files/dirs the agent may edit (the scope_drift allowlist)", "list", ""),
    "scope-set": ("Replace the scope_drift allowlist with these path globs", "set", "<glob>… e.g. 'src/**' 'tests/**'"),
    "scope-add": ("Add path globs to the scope_drift allowlist", "add", "<glob>… e.g. 'src/**' 'tests/**'"),
    "scope-remove": ("Remove path globs from the scope_drift allowlist", "remove", "<glob>… e.g. 'tests/**'"),
}


def _scope_slash_body(description: str, action: str, argument_hint: str) -> str:
    """A `/tycho-scope-*` command file. `list` reuses the generic body; set/add/remove tell
    the agent to single-quote each glob so the shell keeps it literal."""
    if action == "list":
        return _slash_body(description, "scope list")
    cmd = _command_for(f"scope {action}")
    return (
        "---\n"
        f"description: {_q(description)}\n"
        f"argument-hint: {_q(argument_hint)}\n"
        "---\n\n"
        f"{_SLASH_MARKER}\n\n"
        "Update this repo's Tycho edit-scope, then show the command's output verbatim. Run it with "
        "the Bash tool, passing **each glob as a separate single-quoted argument** so the shell keeps "
        "it literal (an unquoted `src/**` expands to files before Tycho stores it):\n\n"
        f"`{cmd} '<glob>' '<glob>' …`\n\n"
        "The globs to use: $ARGUMENTS\n\n"
        "This edits `.tycho.toml` only — it never touches your code.\n"
    )


def _slash_files(repo: Path, scope: str = REPO) -> dict[Path, str]:
    """Path → body for every `/tycho` command file we install (flat `tycho-<sub>.md`)."""
    d = _commands_dir(repo, scope)
    files = {d / "tycho.md": _slash_body(
        "Run Tycho - verify what the agent claimed", "$ARGUMENTS",
        argument_hint="<status|doctor|verify|scope|help>",
    )}
    for name, (desc, args) in _SLASH_SUBCOMMANDS.items():
        files[d / f"tycho-{name}.md"] = _slash_body(desc, args)
    for name, (desc, action, hint) in _SCOPE_SLASH.items():
        files[d / f"tycho-{name}.md"] = _scope_slash_body(desc, action, hint)
    return files


def _install_slash_commands(repo: Path, scope: str = REPO) -> str | None:
    """Write the `/tycho` command set. A command file without our marker is the user's and
    stays put."""
    target = _slash_files(repo, scope)
    d = _commands_dir(repo, scope)
    # Drop our files from the old `tycho/` namespace layout, plus `.bak` clutter — a
    # command file is wholly ours, so it never needed a backup.
    for path in [*_tycho_command_files(repo, scope), *d.glob("tycho*.tycho.bak")]:
        if path not in target and (path.suffix == ".bak" or _SLASH_MARKER in (_current_text(path) or "")):
            path.unlink()
    try:
        (d / "tycho").rmdir()  # tidy the old namespace dir if now empty
    except OSError:
        pass
    installed, skipped = [], []
    for path, body in target.items():
        existing = _current_text(path)
        if existing is not None and _SLASH_MARKER not in existing:
            skipped.append(path.name)
        elif _write_text(path, body, backup=False):
            installed.append(path)
    label = "claude" if scope == REPO else "claude (global)"
    lines = []
    if installed:
        lines.append(f"{label}: installed /tycho slash commands ({len(installed)}) → {d}")
    if skipped:
        lines.append(f"{label}: left your own command file(s) alone: {', '.join(sorted(set(skipped)))}")
    return "\n".join(lines) or None


def _user_statusline_command(repo: Path) -> str | None:
    """The command in the *user-level* Claude settings' statusLine, if any (read-only). The
    repo slot wins over the user-level one, so this tells us whether ours would shadow an
    existing badge. `$HOME` stays a signal, never a write target."""
    try:
        data = json.loads((harness_mod.home("claude") / "settings.json").read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None
    sl = data.get("statusLine") if isinstance(data, dict) else None
    cmd = sl.get("command") if isinstance(sl, dict) else None
    return cmd if isinstance(cmd, str) and not _is_tycho_status(cmd) else None


def _global_statusline(data: dict, path: Path) -> tuple[dict, str]:
    """The user-level status bar: take the slot only if it is empty. Repo scope can compose
    with a foreign line because it owns the write and uninstall puts the original back;
    machine-wide there is no such symmetry, so an occupied slot is left alone."""
    current = data.get("statusLine")
    if isinstance(current, dict) and not _is_tycho_status(current.get("command")):
        return data, ("claude (global): left your user-level statusLine alone — Tycho's badge "
                      "shows in repos where you run `tycho init`")
    base = current if isinstance(current, dict) else {}
    merged = {**base, "type": "command", "command": _command_for("statusline")}
    merged.setdefault("refreshInterval", _STATUS_REFRESH_MS)
    if merged == current:
        return data, ""
    return {**data, "statusLine": merged}, f"claude (global): installed statusLine → {path}"


def _with_statusline(repo: Path, data: dict, path: Path, scope: str = REPO) -> tuple[dict, str]:
    """Claim Claude Code's status bar, *composing* with any existing one.

    `statusLine` holds one command and a repo-level line wins over the user-level one, so
    rather than hide a third-party badge we take the slot and run the other command too. A
    foreign line in this repo's file is recorded (origin "repo") and restored on uninstall;
    a user-level one (origin "user") is left untouched and resurfaces once ours is gone.
    Shape verified against Claude Code 2.1.210: {"type": "command", "command": str}, plus
    optional padding/refreshInterval which are the user's to set — hence the merge.
    """
    if scope == GLOBAL:
        return _global_statusline(data, path)
    current = data.get("statusLine")
    command = status_command()
    ours = isinstance(current, dict) and _is_tycho_status(current.get("command"))
    foreign = current.get("command") if (isinstance(current, dict) and not ours) else None

    if isinstance(foreign, str):
        state.write_statusline_wrap(repo, foreign, origin="repo")
    elif (user_cmd := _user_statusline_command(repo)) is not None:
        state.write_statusline_wrap(repo, user_cmd, origin="user")
    else:
        state.clear_statusline_wrap(repo)

    base = current if (ours and isinstance(current, dict)) else {}  # keep our own extra keys only
    merged = {**base, "type": "command", "command": command}
    # Claude Code renders the badge at the Stop event, which fires while our hook is still
    # verifying — without polling the badge sits on "pending" until the *next* prompt.
    merged.setdefault("refreshInterval", _STATUS_REFRESH_MS)
    if merged == current and state.read_statusline_wrap(repo) is None:
        return data, ""  # already ours, nothing to compose — the Stop-hook line speaks for it
    composing = " (composing with your existing status line)" if state.read_statusline_wrap(repo) else ""
    return {**data, "statusLine": merged}, f"claude: installed statusLine → {path}{composing}"


def _strip_claude_tycho(groups: list) -> tuple[list, bool]:
    """Drop any existing tycho hook entries (and now-empty groups); flag if any removed."""
    out, existed = [], False
    for group in groups:
        entries = (group.get("hooks") or []) if isinstance(group, dict) else []
        kept = [h for h in entries if not (isinstance(h, dict) and _is_tycho_owned(h.get("command")))]
        existed = existed or len(kept) != len(entries)
        if not isinstance(group, dict):
            out.append(group)
        elif kept or not entries:
            out.append({**group, "hooks": kept})
    return out, existed


def _install_cursor(repo: Path) -> str:
    # .cursor/hooks.json → hooks.stop is a flat list of {command, ...}; needs `version`.
    path = config_path(repo, "cursor")
    data = _load(path)
    hooks = dict(data.get("hooks") or {}) if isinstance(data.get("hooks"), dict) else {}
    command = hook_command()
    stop = list(hooks.get("stop") or [])
    kept = [h for h in stop if not (isinstance(h, dict) and _is_tycho_hook(h.get("command")))]
    existed = len(kept) != len(stop)
    kept.append({"command": command})
    hooks["stop"] = kept
    changed = _write(path, {**data, "version": data.get("version", 1), "hooks": hooks})
    state.write_install(repo, "cursor", command)
    return _status("cursor", "stop hook", path, command, existed, changed)


def _install_codex(repo: Path) -> str:
    """Codex shares Claude's hooks shape: `hooks.<Event>` is a list of matcher-groups, and
    its output wire schema clones Claude's. One write, so the
    .bak doesn't churn — same reason `_install_claude` batches its keys.
    """
    path = config_path(repo, "codex")
    data = _load(path)
    hooks = dict(data.get("hooks") or {}) if isinstance(data.get("hooks"), dict) else {}
    command = hook_command()
    groups, existed = _strip_claude_tycho(hooks.get("Stop") or [])
    groups.append({"hooks": [{"type": "command", "command": command}]})
    hooks["Stop"] = groups
    ss_command = _command_for("session-start")
    ss_groups, ss_existed = _strip_claude_tycho(hooks.get("SessionStart") or [])
    ss_groups.append({"hooks": [{"type": "command", "command": ss_command}]})
    hooks["SessionStart"] = ss_groups
    changed = _write(path, {**data, "hooks": hooks})
    state.write_install(repo, "codex", command)
    hook_line = _status("codex", "Stop hook", path, command, existed, changed)
    ss_line = _status("codex", "SessionStart hook", path, ss_command, ss_existed, changed)
    return "\n".join(filter(None, (hook_line, ss_line)))


def _install_opencode(repo: Path) -> str:
    # OpenCode has no Stop hook; a project plugin drives two entrypoints off the event bus,
    # each handed the session id on stdin, toasting via client.tui.showToast:
    #   - session.idle    → `tycho hook`          (the verdict, after every turn)
    #   - session.created → `tycho session-start` (the update notice, once per session)
    # The transcript comes from opencode.db, not `opencode export` (truncates at 128 KB
    # over a pipe).
    path = config_path(repo, "opencode")
    command = hook_argv(hook_command())
    notice = hook_argv(_command_for("session-start"))
    source = f'''{_PLUGIN_MARKER} OpenCode loads project plugins at startup.
const command = {json.dumps(command)}
const noticeCommand = {json.dumps(notice)}

export const TychoPlugin = async ({{ client, directory }}) => {{
  const run = async (argv, sessionID) => {{
    const proc = Bun.spawn([...argv], {{
      cwd: directory, stdin: "pipe", stdout: "pipe", stderr: "ignore",
    }})
    proc.stdin.write(JSON.stringify({{ harness: "opencode", sessionID, directory }}))
    proc.stdin.end()
    const text = (await new Response(proc.stdout).text()).trim()
    await proc.exited
    if (!text) return
    try {{
      const message = JSON.parse(text).message
      if (message) await client.tui.showToast({{
        body: {{ title: "Tycho", message, variant: "info" }},
      }})
    }} catch {{}}
  }}
  return {{
    event: async ({{ event }}) => {{
      if (event.type === "session.idle") {{
        const sessionID = event.properties?.sessionID
        if (sessionID) await run(command, sessionID)
      }} else if (event.type === "session.created") {{
        await run(noticeCommand, event.properties?.sessionID)
      }}
    }},
  }}
}}
'''
    # A hand-written tycho.js is not ours — refuse rather than overwrite it.
    existed = path.exists()
    if existed and _PLUGIN_MARKER not in (_current_text(path) or ""):
        raise ConfigRefused(f"{path} wasn't generated by tycho init — move it aside, then re-run")
    changed = _write_text(path, source)
    state.write_install(repo, "opencode", shlex.join(command))
    return _status("opencode", "session.idle + session.created plugin", path, shlex.join(command), existed, changed)


# --- the git prepare-commit-msg hook (the commit trailer, strategy §6.6) -----


def git_hooks_dir(repo: Path) -> Path | None:
    """This repo's hooks dir, or None when `repo` isn't a git repo (or git is absent). Uses
    `git rev-parse --git-path hooks`, not `<repo>/.git/hooks`: the only spelling correct for
    a plain repo, a linked worktree or submodule (`.git` is a *file*), and `core.hooksPath`.
    """
    try:
        proc = subprocess.run(
            ["git", "-C", str(repo), "rev-parse", "--git-path", "hooks"],
            capture_output=True, text=True, encoding="utf-8", errors="replace",
        )
    except (OSError, ValueError):
        return None  # no git on PATH — nothing to install into, and not an error
    if proc.returncode != 0 or not proc.stdout.strip():
        return None
    path = Path(proc.stdout.strip())
    # `--git-path` answers relative to the command's cwd, which `-C` set to `repo`.
    return path if path.is_absolute() else repo / path


def _git_hook_block() -> str:
    """Our fenced block: one line of work, wrapped so it cannot fail a commit. `|| :`
    swallows a non-zero exit even under a user's `set -e`; stdout/stderr are dropped so a
    traceback can't corrupt the message file; and the block never calls `exit`, so a foreign
    hook we sit in still runs every line. Inserted after the shebang rather than appended,
    since a foreign hook may exit early."""
    return (
        f"{_GIT_BEGIN} — the Tycho-Attestation trailer. Remove with `tycho uninstall`.\n"
        f"# Fails open by construction: it can neither block nor fail this commit.\n"
        f'{attest_command()} "$1" "$2" >/dev/null 2>&1 || :\n'
        f"{_GIT_END}\n"
    )


def _make_executable(path: Path) -> None:
    """Git only runs a hook it can execute. No-op on Windows, where git goes by the shebang
    and `chmod` can't express the bit anyway."""
    try:
        mode = path.stat().st_mode
        path.chmod(mode | ((mode & 0o444) >> 2))  # +x wherever +r — i.e. `chmod +x` under umask
    except OSError:
        pass  # a hooks dir we can't chmod is a hook that won't fire — never a crash


def _install_git_hook(repo: Path) -> str | None:
    """Install/refresh the `prepare-commit-msg` hook. None when there's no repo. Our block
    is replaced in place, never stacked; an existing hook keeps every line; and a hook that
    isn't a `/bin/sh` script is left alone, since we can't reason about where a python or
    compiled hook tolerates an inserted line."""
    hooks = git_hooks_dir(repo)
    if hooks is None:
        return None
    path = hooks / _GIT_HOOK
    current = _current_text(path)
    block = _git_hook_block()
    if current is None:
        text = f"#!/bin/sh\n{block}"
    elif _GIT_BLOCK_RE.search(current):
        text = _GIT_BLOCK_RE.sub(lambda _: block, current, count=1)
    elif not _SH_SHEBANG.match(current.splitlines()[0] if current.splitlines() else ""):
        raise ConfigRefused(
            f"{path} isn't a /bin/sh hook Tycho can extend safely — move it aside and re-run, "
            f"or add `{attest_command()} \"$1\" \"$2\" >/dev/null 2>&1 || :` to it yourself"
        )
    else:
        head, _, rest = current.partition("\n")
        text = f"{head}\n{block}{rest}"
    changed = _write_text(path, text, backup=current is not None)
    _make_executable(path)
    if not changed:
        return f"git: commit trailer hook already current → {path}"
    verb = "installed" if current is None else "added the Tycho block to your"
    return f"git: {verb} {_GIT_HOOK} hook → {path}"


# `.tycho/` is machine-local (tally, heartbeat, and `turns.jsonl`, which carries the
# agent's own prose). None of it is shareable or wanted in someone else's PR.
_IGNORE_ENTRY = ".tycho/"
_IGNORE_NOTE = "# Tycho's machine-local state (tally, heartbeat, turn record)."
_IGNORE_BLOCK = f"{_IGNORE_NOTE}\n{_IGNORE_ENTRY}\n"


def _already_ignored(repo: Path) -> bool:
    """Is `.tycho/` already ignored here, by any means? Asks git rather than scanning
    `.gitignore`: the entry can live in a parent `.gitignore`, `.git/info/exclude`, or the
    global excludesfile. Any error reads as "not ignored"."""
    try:
        proc = subprocess.run(
            ["git", "-C", str(repo), "check-ignore", "-q", _IGNORE_ENTRY],
            capture_output=True,
        )
    except (OSError, ValueError):
        return False
    return proc.returncode == 0


def _install_gitignore(repo: Path) -> str | None:
    """Add `.tycho/` to the repo's `.gitignore`. None when there is nothing to do. Appended
    rather than rewritten, backed up first, and never the reason an install fails."""
    if not gitstate.is_repo(repo) or _already_ignored(repo):
        return None
    path = repo / ".gitignore"
    current = _current_text(path)
    if current is not None and _IGNORE_ENTRY in current.splitlines():
        return None  # present but not effective (negated later, say) — not ours to fight
    if current is None:
        text = _IGNORE_BLOCK
    else:
        tail = "" if current.endswith("\n") else "\n"  # don't glue onto their last line
        text = f"{current}{tail}\n{_IGNORE_BLOCK}"     # blank line, then ours
    if not _write_text(path, text, backup=current is not None):
        return None
    return f"git: ignored {_IGNORE_ENTRY} → {path}"


def _uninstall_gitignore(repo: Path) -> str | None:
    """Take our two lines back out, leaving every other line exactly as it was."""
    path = repo / ".gitignore"
    current = _current_text(path)
    if not current or _IGNORE_BLOCK not in current:
        return None
    # Longest match first, so the blank separator we added comes out with the block —
    # `init; uninstall` must restore the file byte-for-byte.
    for pattern, replacement in ((f"\n\n{_IGNORE_BLOCK}", "\n"), (f"\n{_IGNORE_BLOCK}", "\n"),
                                 (_IGNORE_BLOCK, "")):
        if pattern in current:
            text = current.replace(pattern, replacement, 1)
            break
    else:
        return None
    if not text.strip():
        # Nothing survives but whitespace, so the file was ours.
        try:
            path.unlink()
        except OSError:
            return None
        return f"git: removed the {path.name} Tycho created → {path}"
    if not _write_text(path, text, backup=True):
        return None
    return f"git: stopped ignoring {_IGNORE_ENTRY} → {path}"


def _uninstall_git_hook(repo: Path) -> str | None:
    """Take our block back out. Restores the file byte-for-byte, or deletes it if it was
    ours — "ours" meaning nothing survives removal but the shebang we wrote."""
    hooks = git_hooks_dir(repo)
    if hooks is None:
        return None
    path = hooks / _GIT_HOOK
    current = _current_text(path)
    if current is None or not _GIT_BLOCK_RE.search(current):
        return None  # nothing of ours here — stay quiet rather than claim a removal
    remainder = _GIT_BLOCK_RE.sub("", current, count=1)
    if remainder.strip() in ("", "#!/bin/sh"):
        try:
            path.unlink()
            path.with_name(path.name + _BACKUP_SUFFIX).unlink(missing_ok=True)
        except OSError as exc:
            raise ConfigRefused(f"cannot remove {path} ({exc.strerror}) — fix that, then re-run") from exc
        return f"git: removed {_GIT_HOOK} hook → {path}"
    _write_text(path, remainder)
    return f"git: removed the Tycho block from {path}"


# --- uninstall ---------------------------------------------------------------
#
# We never delete a harness's config file — it may hold settings we didn't write. Remove
# our entries, then drop a container only when it's empty *and* we would have created it.
# The OpenCode plugin is the exception: that whole file is ours, so it goes.


def _prune(data: dict, hooks: dict, key: str, kept: list) -> dict:
    """Put `kept` back under `key`, dropping containers we emptied."""
    if kept:
        hooks[key] = kept
    else:
        hooks.pop(key, None)  # init created this list; don't leave an empty one behind
    merged = {**data, "hooks": hooks}
    if not hooks:
        merged.pop("hooks", None)
    return merged


def _uninstall_claude(repo: Path, scope: str = REPO) -> str:
    """Take back our hooks and statusLine — only ours, in one write, or the backup churns
    (same reason install batches them). Scope-symmetric with `_install_claude`:
    `_is_tycho_owned` matches a guarded global command exactly as a bare repo-local one."""
    label = "claude" if scope == REPO else "claude (global)"
    path = settings_path(repo, scope)
    if not path.exists():
        return f"{label}: nothing to remove (no config)"
    data = _load(path)
    hooks = dict(data.get("hooks") or {}) if isinstance(data.get("hooks"), dict) else {}
    groups, had_hook = _strip_claude_tycho(hooks.get("Stop") or [])
    ss_groups, had_ss = _strip_claude_tycho(hooks.get("SessionStart") or [])
    ups_groups, had_ups = _strip_claude_tycho(hooks.get("UserPromptSubmit") or [])
    current = data.get("statusLine")
    had_statusline = isinstance(current, dict) and _is_tycho_status(current.get("command"))
    slash = _uninstall_slash_commands(repo, scope)
    # A global install never wrote a compose record, and clearing the *repo's* would be wrong.
    wrap = state.read_statusline_wrap(repo) if scope == REPO else None
    if scope == REPO:
        state.clear_statusline_wrap(repo)  # forget the compose target either way
    if not had_hook and not had_ss and not had_ups and not had_statusline:
        return slash or f"{label}: nothing to remove"
    _prune(data, hooks, "Stop", groups)  # mutates `hooks` in place…
    _prune(data, hooks, "SessionStart", ss_groups)  # …then the second key…
    merged = _prune(data, hooks, "UserPromptSubmit", ups_groups)  # …then the third
    restored = False
    if had_statusline:
        merged = {k: v for k, v in merged.items() if k != "statusLine"}
        # A foreign repo-level line we replaced is ours to put back; a user-level one
        # resurfaces on its own.
        if isinstance(wrap, dict) and wrap.get("origin") == "repo" and isinstance(wrap.get("command"), str):
            merged = {**merged, "statusLine": {"type": "command", "command": wrap["command"]}}
            restored = True
    _write(path, merged)
    lines = []
    if had_hook:
        lines.append(f"{label}: removed Stop hook → {path}")
    if had_ss:
        lines.append(f"{label}: removed SessionStart hook → {path}")
    if had_ups:
        lines.append(f"{label}: removed UserPromptSubmit hook → {path}")
    if had_statusline:
        lines.append(f"{label}: restored your statusLine → {path}" if restored
                     else f"{label}: removed statusLine → {path}")
    if slash:
        lines.append(slash)
    return "\n".join(lines)


def _tycho_command_files(repo: Path, scope: str = REPO) -> list[Path]:
    """Every command file that could be ours — the flat `tycho.md`/`tycho-*.md` plus the old
    namespaced `tycho/*.md`, so uninstall cleans both layouts."""
    d = _commands_dir(repo, scope)
    return [*d.glob("tycho.md"), *d.glob("tycho-*.md"), *(d / "tycho").glob("*.md")]


def _uninstall_slash_commands(repo: Path, scope: str = REPO) -> str | None:
    """Remove every `/tycho` command we generated; leave hand-written files alone."""
    d = _commands_dir(repo, scope)
    removed = False
    for path in _tycho_command_files(repo, scope):
        text = _current_text(path)
        if text is not None and _SLASH_MARKER in text:
            path.unlink()
            removed = True
    for tidy in (d / "tycho", d):
        try:
            tidy.rmdir()  # only if now empty — never take a dir holding someone's file
        except OSError:
            pass
    label = "claude" if scope == REPO else "claude (global)"
    return f"{label}: removed /tycho slash commands → {d}" if removed else None


def _uninstall_codex(repo: Path) -> str:
    """Remove the Stop and SessionStart hooks — only ours, in one write."""
    path = repo / ".codex" / "hooks.json"
    if not path.exists():
        return "codex: nothing to remove (no config)"
    data = _load(path)
    hooks = dict(data.get("hooks") or {}) if isinstance(data.get("hooks"), dict) else {}
    groups, had_hook = _strip_claude_tycho(hooks.get("Stop") or [])
    ss_groups, had_ss = _strip_claude_tycho(hooks.get("SessionStart") or [])
    if not had_hook and not had_ss:
        return "codex: nothing to remove"
    _prune(data, hooks, "Stop", groups)  # mutates `hooks` in place…
    merged = _prune(data, hooks, "SessionStart", ss_groups)  # …then the second key
    _write(path, merged)
    lines = []
    if had_hook:
        lines.append(f"codex: removed Stop hook → {path}")
    if had_ss:
        lines.append(f"codex: removed SessionStart hook → {path}")
    return "\n".join(lines)


def _uninstall_cursor(repo: Path) -> str:
    # .cursor/hooks.json → hooks.stop is a flat list of {command, ...}.
    path = repo / ".cursor" / "hooks.json"
    if not path.exists():
        return "cursor: nothing to remove (no config)"
    data = _load(path)
    hooks = dict(data.get("hooks") or {}) if isinstance(data.get("hooks"), dict) else {}
    stop = list(hooks.get("stop") or [])
    kept = [h for h in stop if not (isinstance(h, dict) and _is_tycho_hook(h.get("command")))]
    if len(kept) == len(stop):
        return "cursor: nothing to remove"
    _write(path, _prune(data, hooks, "stop", kept))
    return f"cursor: removed stop hook → {path}"


def _uninstall_opencode(repo: Path) -> str:
    # The whole plugin file is ours — but only if we generated it.
    path = repo / ".opencode" / "plugins" / "tycho.js"
    if not path.exists():
        return "opencode: nothing to remove"
    try:
        generated = _PLUGIN_MARKER in path.read_text(encoding="utf-8")
    except OSError:
        generated = False
    if not generated:
        return f"opencode: left {path} alone (not generated by tycho init)"
    path.unlink()
    try:
        path.parent.rmdir()  # tidy the plugins/ dir we made — only if now empty
    except OSError:
        pass  # user has other plugins, or the dir predates us: leave it
    return f"opencode: removed plugin → {path}"
